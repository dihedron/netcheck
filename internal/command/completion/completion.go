// Package completion prints the shell completion scripts of the command: bash,
// zsh, fish and PowerShell. The scripts are static, built from the option
// parser: pressing TAB never runs netcheck.
package completion

import (
	"fmt"
	"io"
	"reflect"
	"sort"
	"strings"

	flags "github.com/jessevdk/go-flags"
)

const program = "netcheck"

// option is what a completion needs to know about a command line option.
type option struct {
	short       string // without the dash; empty when there is none
	long        string // without the dashes
	description string
	choices     []string // the values it accepts; empty when any
	takesValue  bool
	file        bool // its value is a file name
}

// subcommand is a word the command answers before it parses its options.
type subcommand struct {
	name, description string
	options           []option
	words             []string // what follows it, when it is a closed list
}

var subcommands = []subcommand{
	{name: "version", description: "print the version of the application", options: []option{
		{short: "v", long: "verbose", description: "print verbose information"},
		{short: "D", long: "dotenv", description: "the path to the .env file", takesValue: true, file: true}}},
	{name: "completion", description: "print the completion script of a shell", words: shells},
}

var shells = []string{"bash", "fish", "powershell", "zsh"}

// options reads the options of the parser, the help flag included, and adds --version.
func options(p *flags.Parser) []option {
	var out []option
	var walk func(*flags.Group)
	walk = func(g *flags.Group) {
		for _, o := range g.Options() {
			x := option{long: o.LongName, description: o.Description, choices: o.Choices, takesValue: o.Field().Type.Kind() != reflect.Bool, file: o.ValueName == "FILE"}
			if o.ShortName != 0 {
				x.short = string(o.ShortName)
			}
			out = append(out, x)
		}
		for _, c := range g.Groups() {
			walk(c)
		}
	}
	walk(p.Command.Group)
	out = append(out, option{long: "version", description: "print the version and exit"})
	if !has(out, "help") { // the parser adds its help group lazily
		out = append(out, option{short: "h", long: "help", description: "show the help message"})
	}
	sort.SliceStable(out, func(i, j int) bool { return out[i].long < out[j].long })
	return out
}

// Run prints the script of the shell named in args and returns the exit code.
func Run(args []string, p *flags.Parser, stdout, stderr io.Writer) int {
	usage := func(why string) int {
		fmt.Fprintf(stderr, "%s\nusage: %s completion %s\n", why, program, strings.Join(shells, "|"))
		return 1
	}
	if len(args) == 0 {
		return usage("no shell given")
	}
	if len(args) > 1 {
		return usage("too many arguments")
	}
	gen := map[string]func(io.Writer, []option){"bash": bash, "zsh": zsh, "fish": fish, "powershell": powershell}[args[0]]
	if gen == nil {
		return usage(fmt.Sprintf("unknown shell %q", args[0]))
	}
	gen(stdout, options(p))
	return 0
}

// singleLine makes a description fit on one line.
func singleLine(s string) string {
	return strings.Join(strings.Fields(s), " ")
}

// quoteSh quotes s as one word for sh, bash, zsh and fish-compatible single quotes: '...' with ' as '\”.
func quoteSh(s string) string {
	return "'" + strings.ReplaceAll(singleLine(s), "'", `'\''`) + "'"
}

// quoteZsh quotes s for use inside a zsh _arguments description: the brackets
// and the colon are escaped for _arguments, then the word is single-quoted.
func quoteZsh(s string) string {
	r := strings.NewReplacer(`\`, `\\`, "[", `\[`, "]", `\]`, ":", `\:`)
	return quoteSh(r.Replace(singleLine(s)))
}

// quoteFish quotes s for fish: single quotes, where only \ and ' are special.
func quoteFish(s string) string {
	r := strings.NewReplacer(`\`, `\\`, "'", `\'`)
	return "'" + r.Replace(singleLine(s)) + "'"
}

// quotePS quotes s for PowerShell: single quotes, with ' doubled.
func quotePS(s string) string {
	return "'" + strings.ReplaceAll(singleLine(s), "'", "''") + "'"
}

func flagsOf(opts []option) (words []string) {
	for _, o := range opts {
		words = append(words, "--"+o.long)
		if o.short != "" {
			words = append(words, "-"+o.short)
		}
	}
	return words
}

func bash(w io.Writer, opts []option) {
	fmt.Fprintf(w, "# bash completion for %s; generated by \"%s completion bash\"\n", program, program)
	fmt.Fprintf(w, "_%s() {\n", program)
	fmt.Fprint(w, "\tlocal cur=\"${COMP_WORDS[COMP_CWORD]}\" prev=\"\"\n")
	fmt.Fprint(w, "\t((COMP_CWORD > 0)) && prev=\"${COMP_WORDS[COMP_CWORD-1]}\"\n")
	fmt.Fprint(w, "\tCOMPREPLY=()\n")
	fmt.Fprint(w, "\tcase \"${COMP_WORDS[1]}\" in\n")
	for _, s := range subcommands {
		fmt.Fprintf(w, "\t%s)\n", s.name)
		if len(s.words) > 0 {
			fmt.Fprintf(w, "\t\t((COMP_CWORD == 2)) && COMPREPLY=($(compgen -W %s -- \"$cur\"))\n", quoteSh(strings.Join(s.words, " ")))
		} else {
			fmt.Fprintf(w, "\t\tCOMPREPLY=($(compgen -W %s -- \"$cur\"))\n", quoteSh(strings.Join(flagsOf(s.options), " ")))
		}
		fmt.Fprint(w, "\t\treturn 0 ;;\n")
	}
	fmt.Fprint(w, "\tesac\n")
	fmt.Fprint(w, "\tcase \"$prev\" in\n")
	for _, o := range opts {
		if !o.takesValue {
			continue
		}
		names := "--" + o.long
		if o.short != "" {
			names += "|-" + o.short
		}
		switch {
		case len(o.choices) > 0:
			fmt.Fprintf(w, "\t%s)\n\t\tCOMPREPLY=($(compgen -W %s -- \"$cur\")); return 0 ;;\n", names, quoteSh(strings.Join(o.choices, " ")))
		case o.file:
			fmt.Fprintf(w, "\t%s)\n\t\tCOMPREPLY=($(compgen -f -- \"$cur\")); return 0 ;;\n", names)
		default:
			fmt.Fprintf(w, "\t%s)\n\t\treturn 0 ;;\n", names)
		}
	}
	fmt.Fprint(w, "\tesac\n")
	fmt.Fprint(w, "\tif [[ \"$cur\" == -* ]]; then\n")
	fmt.Fprintf(w, "\t\tCOMPREPLY=($(compgen -W %s -- \"$cur\"))\n", quoteSh(strings.Join(flagsOf(opts), " ")))
	fmt.Fprint(w, "\t\treturn 0\n\tfi\n")
	var names []string
	for _, s := range subcommands {
		names = append(names, s.name)
	}
	fmt.Fprint(w, "\tif ((COMP_CWORD == 1)); then\n")
	fmt.Fprintf(w, "\t\tCOMPREPLY=($(compgen -W %s -- \"$cur\"))\n\tfi\n", quoteSh(strings.Join(names, " ")))
	fmt.Fprint(w, "\tCOMPREPLY+=($(compgen -f -- \"$cur\"))\n")
	fmt.Fprint(w, "\treturn 0\n}\n")
	fmt.Fprintf(w, "complete -o filenames -F _%s %s\n", program, program)
}

func zsh(w io.Writer, opts []option) {
	fmt.Fprintf(w, "#compdef %s\n# zsh completion for %s; generated by \"%s completion zsh\"\n", program, program, program)
	fmt.Fprintf(w, "_%s() {\n", program)
	fmt.Fprint(w, "\tlocal -a args cmds\n\tlocal state state_descr line\n\targs=(\n")
	for _, o := range opts {
		spec := ""
		desc := "[" + strings.Trim(quoteZsh(o.description), "'") + "]"
		switch {
		case len(o.choices) > 0:
			spec = fmt.Sprintf(":%s:(%s)", o.long, strings.Join(o.choices, " "))
		case o.file:
			spec = ":file:_files"
		case o.takesValue:
			spec = ":" + o.long + ": "
		}
		if o.short != "" {
			fmt.Fprintf(w, "\t\t'(-%s --%s)'{-%s,--%s}%s\n", o.short, o.long, o.short, o.long, quoteSh(desc+spec))
		} else {
			fmt.Fprintf(w, "\t\t%s\n", quoteSh("--"+o.long+desc+spec))
		}
	}
	fmt.Fprint(w, "\t\t'1: :->first'\n\t\t'*:bundle:_files'\n\t)\n")
	fmt.Fprint(w, "\tcmds=(")
	for i, s := range subcommands {
		if i > 0 {
			fmt.Fprint(w, " ")
		}
		fmt.Fprint(w, quoteSh(s.name+":"+strings.ReplaceAll(singleLine(s.description), ":", `\:`)))
	}
	fmt.Fprint(w, ")\n")
	fmt.Fprint(w, "\t_arguments -S $args\n")
	fmt.Fprint(w, "\tif [[ $state == first ]]; then\n\t\t_describe 'command' cmds\n\t\t_files\n\tfi\n")
	fmt.Fprint(w, "}\n")
	fmt.Fprintf(w, "_%s \"$@\"\n", program)
}

func fish(w io.Writer, opts []option) {
	fmt.Fprintf(w, "# fish completion for %s; generated by \"%s completion fish\"\n", program, program)
	for _, o := range opts {
		line := fmt.Sprintf("complete -c %s -l %s", program, o.long)
		if o.short != "" {
			line += " -s " + o.short
		}
		line += " -d " + quoteFish(o.description)
		switch {
		case len(o.choices) > 0:
			line += " -x -a " + quoteFish(strings.Join(o.choices, " "))
		case o.file:
			line += " -r -F"
		case o.takesValue:
			line += " -x"
		}
		fmt.Fprintln(w, line)
	}
	for _, s := range subcommands {
		fmt.Fprintf(w, "complete -c %s -n '__fish_use_subcommand' -a %s -d %s\n", program, quoteFish(s.name), quoteFish(s.description))
		if len(s.words) > 0 {
			fmt.Fprintf(w, "complete -c %s -n '__fish_seen_subcommand_from %s' -x -a %s\n", program, s.name, quoteFish(strings.Join(s.words, " ")))
		}
		for _, o := range s.options {
			line := fmt.Sprintf("complete -c %s -n '__fish_seen_subcommand_from %s' -l %s -s %s -d %s", program, s.name, o.long, o.short, quoteFish(o.description))
			if o.file {
				line += " -r -F"
			}
			fmt.Fprintln(w, line)
		}
	}
}

func powershell(w io.Writer, opts []option) {
	fmt.Fprintf(w, "# PowerShell completion for %s; generated by \"%s completion powershell\"\n", program, program)
	fmt.Fprintf(w, "Register-ArgumentCompleter -Native -CommandName %s -ScriptBlock {\n", program)
	fmt.Fprint(w, "\tparam($wordToComplete, $commandAst, $cursorPosition)\n")
	fmt.Fprint(w, "\t$words = $commandAst.CommandElements | ForEach-Object { $_.ToString() }\n")
	fmt.Fprint(w, "\t$candidates = @()\n")
	fmt.Fprint(w, "\tif ($words.Count -ge 2 -and $words[1] -eq 'completion') {\n")
	fmt.Fprintf(w, "\t\t$candidates = @(%s)\n", psList(shells, nil))
	fmt.Fprint(w, "\t} else {\n")
	fmt.Fprint(w, "\t\t$previous = if ($words.Count -ge 2) { $words[$words.Count - 1] } else { '' }\n")
	for _, o := range opts {
		if len(o.choices) == 0 {
			continue
		}
		cond := "$previous -eq '--" + o.long + "'"
		if o.short != "" {
			cond += " -or $previous -eq '-" + o.short + "'"
		}
		fmt.Fprintf(w, "\t\tif (%s) { $candidates = @(%s) } else", cond, psList(o.choices, nil))
	}
	fmt.Fprint(w, " {\n")
	var items []string
	for _, o := range opts {
		items = append(items, "@("+quotePS("--"+o.long)+", "+quotePS(o.description)+")")
		if o.short != "" {
			items = append(items, "@("+quotePS("-"+o.short)+", "+quotePS(o.description)+")")
		}
	}
	for _, s := range subcommands {
		items = append(items, "@("+quotePS(s.name)+", "+quotePS(s.description)+")")
	}
	fmt.Fprintf(w, "\t\t\t$candidates = @(\n\t\t\t\t%s\n\t\t\t)\n", strings.Join(items, ",\n\t\t\t\t"))
	fmt.Fprint(w, "\t\t}\n\t}\n")
	fmt.Fprint(w, "\t$candidates | Where-Object { $name = if ($_ -is [array]) { $_[0] } else { $_ }; $name -like \"$wordToComplete*\" } | ForEach-Object {\n")
	fmt.Fprint(w, "\t\t$name = if ($_ -is [array]) { $_[0] } else { $_ }\n")
	fmt.Fprint(w, "\t\t$tip = if ($_ -is [array]) { $_[1] } else { $_ }\n")
	fmt.Fprint(w, "\t\t[System.Management.Automation.CompletionResult]::new($name, $name, 'ParameterValue', $tip)\n")
	fmt.Fprint(w, "\t}\n}\n")
}

func psList(words []string, _ []string) string {
	q := make([]string, len(words))
	for i, w := range words {
		q[i] = quotePS(w)
	}
	return strings.Join(q, ", ")
}

func has(opts []option, long string) bool {
	for _, o := range opts {
		if o.long == long {
			return true
		}
	}
	return false
}
